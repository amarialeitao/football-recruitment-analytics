"""AI Scouting Note block for the Player Profile page.

Renders nothing unless the feature is enabled and configured (see :mod:`scouting.llm_notes`).
"""

from __future__ import annotations

import html
import json
from collections.abc import Iterable

import pandas as pd
import streamlit as st

from scouting.config import Settings
from scouting.insights import Insight
from scouting.llm_notes import LLMUnavailableError, build_facts, generate_note, is_available
from scouting.ui.i18n import Lang

TEXT = {
    "title": {"en": "AI Scouting Note", "pt": "Nota de scouting por IA"},
    "button": {"en": "Generate note", "pt": "Gerar nota"},
    "disclaimer": {
        "en": "Generated by an AI model ({model}) from the metrics on this page only. It may "
        "contain errors; check it against the charts before using it.",
        "pt": "Gerado por um modelo de IA ({model}) apenas a partir das métricas desta página. "
        "Pode conter erros; confirme com os gráficos antes de o usar.",
    },
    "warning": {
        "en": "Some numbers in the note were not found in the metrics: {items}",
        "pt": "Alguns números da nota não constam das métricas: {items}",
    },
    "error": {
        "en": "The note could not be generated: {error}",
        "pt": "Não foi possível gerar a nota: {error}",
    },
}


@st.cache_data(show_spinner=False, max_entries=200)
def _cached_note(facts_json: str, lang: str, _settings: Settings) -> dict:
    note = generate_note(json.loads(facts_json), lang, _settings.llm)
    return note.__dict__


def ai_note_block(
    row: pd.Series,
    *,
    settings: Settings,
    lang: Lang,
    confidence: str,
    insights: Iterable[Insight],
    league_strength_index: float | None = None,
) -> None:
    """Show the button and the note when the feature is available; otherwise render nothing."""
    if not is_available(settings.llm):
        return
    facts = build_facts(
        row,
        confidence=confidence,
        insights=insights,
        league_strength_index=league_strength_index,
    )
    with st.container(border=True):
        st.markdown(f"**{TEXT['title'][lang]}**")
        if not st.button(TEXT["button"][lang], key=f"ai_note_{row['player_id']}_{lang}"):
            return
        try:
            with st.spinner("…"):
                note = _cached_note(json.dumps(facts, sort_keys=True), lang, settings)
        except LLMUnavailableError as error:
            st.info(TEXT["error"][lang].format(error=error))
            return
        except Exception as error:  # network or API errors must not break the page
            st.warning(TEXT["error"][lang].format(error=type(error).__name__))
            return
        st.markdown(html.escape(note["text"]))
        st.caption(TEXT["disclaimer"][lang].format(model=note["model"]))
        if note["warnings"]:
            items = ", ".join(w.rsplit(": ", 1)[-1] for w in note["warnings"])
            st.warning(TEXT["warning"][lang].format(items=items))
