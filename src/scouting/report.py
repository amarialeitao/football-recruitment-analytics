"""One-page player report: a self-contained HTML page to share or print as PDF.

It is what a scout would send to a sporting director: who the player is, what he does compared
with his peers, how that changed since last season, what the market says, how sure we can be,
and what the data cannot show. Everything comes from numbers the app already computed; the
report adds no new judgement.

The page has no external files (styles inline, bars drawn with HTML), so it opens offline, can
be attached to an e-mail and prints on one A4 page from any browser ("Save as PDF").
"""

