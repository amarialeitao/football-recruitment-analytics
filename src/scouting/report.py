def _t(key: str, lang: str) -> str:
    return TEXT[key]["pt" if lang == "pt" else "en"]


def _e(value: object) -> str:
    return html.escape(str(value))


@dataclass(frozen=True)
class ReportInput:
    row: pd.Series  # the player-season row, with percentiles and value columns
    profile_keys: Sequence[str]
    insights: Sequence[Insight]
    min_minutes: int
    confidence: str  # from minutes played
    data_cutoff: pd.Timestamp
    season_label: str
    strength_index: float | None = None
    trend_insights: Sequence[Insight] = field(default_factory=tuple)
    trend_note: str | None = None  # why there is no comparison, when there is none
    previous_season_label: str | None = None


def _fact(value: str, label: str, note: str = "") -> str:
    note_html = f'<div class="note">{_e(note)}</div>' if note else ""
    return (
        f'<div class="fact"><div class="value">{_e(value)}</div>'
        f'<div class="label">{_e(label)}</div>{note_html}</div>'
    )


def _bars(row: pd.Series, keys: Sequence[str], lang: str) -> str:
    out = []
    for key in keys:
        pct = row.get(key + PCT_SUFFIX)
        raw = row.get(key)
        m = metric(key)
        raw_text = "—" if raw is None or pd.isna(raw) else m.fmt.format(float(raw))
        if pct is None or pd.isna(pct):
            width, pct_text = 0.0, "—"
        else:
            width, pct_text = max(0.0, min(100.0, float(pct))), f"{float(pct):.0f}"
        out.append(
            '<div class="bar-row">'
            f'<div class="bar-label">{_e(m.label_for(lang))}</div>'
            f'<div class="bar-track"><div class="bar-fill" style="width:{width:.1f}%"></div>'
            '<div class="bar-median"></div></div>'
            f'<div class="bar-pct">{_e(pct_text)}</div>'
            f'<div class="bar-raw">{_e(raw_text)}</div>'
            "</div>"
        )
    return "".join(out)


def _insight_items(insights: Sequence[Insight], lang: str, limit: int) -> str:
    items = []
    for insight in list(insights)[:limit]:
        level = insight.confidence
        items.append(
            f'<li>{_e(insight.render(lang))} <span class="badge badge-{_e(level)}">'
            f"{_e(CONFIDENCE_LABEL[lang][level])}</span></li>"
        )
    return f"<ul>{''.join(items)}</ul>" if items else ""


def player_report_html(report: ReportInput, lang: str = "en") -> str:
    """The report as one self-contained HTML document."""
    lang = "pt" if lang == "pt" else "en"
    row = report.row
    group = row.get("position_group")
    group_label = POSITION_LABEL[lang].get(group, "") if isinstance(group, str) else ""
    contract = row.get("contract_expiration_date")
    share = row.get("minutes_share")
    share_text = "—" if share is None or pd.isna(share) else f"{float(share):.0%}"
    conf_text = CONFIDENCE_LABEL[lang][report.confidence]

    facts = [
        _fact(
            num(row.get("age"), lang, 1),
            _t("age", lang),
            _t("age_note", lang).format(year=int(row["season"]) + 1),
        ),
        _fact(
            num(row.get("minutes"), lang),
            _t("minutes", lang),
            _t("minutes_note", lang).format(share=share_text, conf=conf_text),
        ),
        _fact(
            format_money(row.get("market_value_end"), lang),
            _t("value", lang),
            _t("value_note", lang).format(start=format_money(row.get("market_value_start"), lang)),
        ),
    ]
    ratio = row.get("value_ratio")
    if ratio is not None and not pd.isna(ratio):
        facts.append(
            _fact(
                f"{num(float(ratio), lang, 2)}x",
                _t("expected", lang),
                _t("expected_note", lang).format(
                    value=format_money(row.get("expected_market_value"), lang)
                ),
            )
        )
    facts.append(
        _fact(
            "—"
            if contract is None or pd.isna(contract)
            else pd.Timestamp(contract).date().isoformat(),
            _t("contract", lang),
            "" if contract is not None and not pd.isna(contract) else _t("contract_none", lang),
        )
    )
    if report.strength_index is not None and not pd.isna(report.strength_index):
        facts.append(
            _fact(num(report.strength_index, lang), _t("league", lang), _t("league_note", lang))
        )

    has_profile = bool(report.profile_keys) and row.get("minutes", 0) >= report.min_minutes
    if has_profile:
        n = row.get("comparison_n")
        profile_html = (
            "<p class='small'>"
            + _e(
                _t("profile_note", lang).format(
                    n=num(n, lang), group=group_label, min=num(report.min_minutes, lang)
                )
            )
            + "</p>"
            f"{_bars(row, report.profile_keys, lang)}"
        )
    else:
        none_text = _t("profile_none", lang).format(min=num(report.min_minutes, lang))
        profile_html = f"<p class='small'>{_e(none_text)}</p>"

    trend_html = ""
    if report.trend_insights:
        trend_html = (
            f"<h2>{_e(_t('trend', lang).format(season=report.previous_season_label or ''))}</h2>"
            f"{_insight_items(report.trend_insights, lang, 4)}"
        )
    elif report.trend_note:
        heading = (
            _t("trend", lang).format(season=report.previous_season_label)
            if report.previous_season_label
            else _t("trend_generic", lang)
        )
        trend_html = f"<h2>{_e(heading)}</h2><p class='small'>{_e(report.trend_note)}</p>"

    insights_html = _insight_items(sort_insights(report.insights), lang, MAX_INSIGHTS)
    missing = "".join(f"<li>{_e(item[lang])}</li>" for item in UNAVAILABLE_METRICS)
    subtitle = " · ".join(
        part
        for part in (
            position_label(row.get("sub_position"), lang),
            f"{row.get('club_name', '')} ({row.get('competition_name', '')})",
            report.season_label,
        )
        if part and part != "—"
    )
    title = f"{row.get('name', '')} · {_t('kind', lang)}"

    return f"""<!doctype html>
<html lang="{lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{_e(title)}</title>
<style>
  @page {{ size: A4; margin: 12mm; }}
  * {{ box-sizing: border-box; }}
  body {{ font-family: Inter, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; color: {INK};
    margin: 0 auto; max-width: 820px; padding: 24px; font-size: 13px; line-height: 1.45;
    background: #fff; }}
  header {{ border-top: 6px solid {INK}; padding-top: 12px; margin-bottom: 14px; }}
  .kind {{ color: {ACCENT}; font-weight: 700; letter-spacing: .06em; text-transform: uppercase;
    font-size: 11px; }}
  h1 {{ font-size: 26px; margin: 2px 0 2px; }}
  .subtitle {{ color: {MUTED}; font-size: 14px; }}
  h2 {{ font-size: 14px; margin: 16px 0 6px; padding-bottom: 3px;
    border-bottom: 1px solid {BORDER}; }}
  .facts {{ display: grid; grid-template-columns: repeat(3, 1fr); gap: 8px; }}
  .fact {{ border: 1px solid {BORDER}; border-top: 3px solid {INK}; border-radius: 6px;
    padding: 8px 10px; }}
  .fact .value {{ font-size: 18px; font-weight: 700; }}
  .fact .label {{ font-size: 11.5px; }}
  .fact .note {{ font-size: 10.5px; color: {MUTED}; }}
  .small {{ font-size: 11px; color: {MUTED}; margin: 2px 0 6px; }}
  .bar-row {{ display: grid; grid-template-columns: 210px 1fr 32px 70px; gap: 8px;
    align-items: center;
    margin: 3px 0; }}
  .bar-label {{ font-size: 12px; }}
  .bar-track {{ position: relative; height: 12px; background: {SURFACE_ALT}; border-radius: 2px; }}
  .bar-fill {{ height: 100%; background: {INK}; border-radius: 2px; }}
  .bar-median {{ position: absolute; left: 50%; top: -3px; bottom: -3px;
    border-left: 1px dashed {MUTED}; }}
  .bar-pct {{ font-weight: 700; text-align: right; }}
  .bar-raw {{ color: {MUTED}; font-size: 11px; }}
  ul {{ margin: 4px 0; padding-left: 18px; }}
  li {{ margin: 2px 0; }}
  .badge {{ font-size: 10px; font-weight: 600; border: 1px solid currentColor; border-radius: 999px;
    padding: 0 6px; white-space: nowrap; }}
  .badge-high {{ color: {OK}; }}
  .badge-medium {{ color: {ATTENTION}; }}
  .badge-low {{ color: {MUTED}; }}
  .missing li {{ color: {MUTED}; }}
  footer {{ margin-top: 16px; padding-top: 8px; border-top: 1px solid {BORDER}; font-size: 10.5px;
    color: {MUTED}; }}
  @media print {{ body {{ padding: 0; }} }}
</style>
</head>
<body>
<header>
  <div class="kind">{_e(_t("kind", lang))}</div>
  <h1>{_e(row.get("name", ""))}</h1>
  <div class="subtitle">{_e(subtitle)}</div>
</header>
<section class="facts">{"".join(facts)}</section>
<h2>{_e(_t("profile", lang))}</h2>
{profile_html}
{trend_html}
<h2>{_e(_t("observations", lang))}</h2>
{insights_html}
<h2>{_e(_t("missing", lang))}</h2>
<p class="small">{_e(_t("missing_note", lang))}</p>
<ul class="missing">{missing}</ul>
<footer>{_e(_t("footer", lang).format(cutoff=report.data_cutoff.date().isoformat()))}</footer>
</body>
</html>
"""


def report_filename(row: pd.Series, season_label: str) -> str:
    """Safe ASCII file name, e.g. 'report_gaizka-larrazabal_2025-26.html'."""
    name = unicodedata.normalize("NFKD", str(row.get("name", "player")).translate(_TRANSLITERATE))
    slug = re.sub(r"[^a-z0-9]+", "-", name.encode("ascii", "ignore").decode().lower()).strip("-")
    return f"report_{slug or 'player'}_{season_label.replace('/', '-')}.html"
